import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';

test('官方仅获取一次 API，草稿状态原样透传，路由观察错误不影响官方', async () => {
  let calls = 0;
  let state = { draft: 'unsent message' };
  const messages = [];
  const context = vm.createContext({
    document: { querySelector() { return { content: '/local/initial' }; } }, queueMicrotask, URLSearchParams,
    acquireVsCodeApi() {
      calls += 1;
      if (calls > 1) throw new Error('already acquired');
      return Object.freeze({ postMessage(message) { messages.push(message); },
        getState() { return state; }, setState(value) { state = value; return value; } });
    },
  });
  vm.runInContext(await fs.readFile(new URL('../webview/bootstrap.js', import.meta.url), 'utf8'), context);
  assert.equal(calls, 0);
  const officialApi = vm.runInContext('acquireVsCodeApi()', context);
  assert.equal(officialApi.getState().draft, 'unsent message');
  officialApi.setState({ draft: 'updated' });
  assert.equal(state.draft, 'updated');
  const bridge = context.__vscodexLayerBridge;
  const container = { isConnected: true };
  assert.throws(() => bridge.openThreadMenu({ id: 'other' }, container), /尚未就绪/);
  const surface = {};
  const releaseMenu = bridge.registerThreadMenuSurface(surface);
  bridge.openThreadMenu({ id: 'other', title: '其他聊天', cwd: '/other' }, container);
  assert.equal(bridge.threadMenuTarget().thread.id, 'other');
  assert.equal(bridge.threadMenuTarget().thread.hostId, 'local');
  const previousToken = bridge.threadMenuTarget().token;
  let menuError;
  const unsubscribeError = bridge.subscribeThreadMenuError((message) => { menuError = message; });
  bridge.openThreadMenu({ id: 'next' }, container);
  bridge.threadMenuError('旧菜单失败', previousToken);
  await new Promise((resolve) => setImmediate(resolve));
  assert.equal(menuError, undefined, '旧菜单的异步失败不能关闭新菜单');
  bridge.threadMenuError('当前失败', bridge.threadMenuTarget().token);
  await new Promise((resolve) => setImmediate(resolve));
  assert.equal(menuError, '当前失败');
  unsubscribeError();
  const choose = () => {};
  const items = bridge.filterThreadMenu([
    { id: 'rename-thread', onSelect: choose }, { id: 'share-thread', enabled: false },
    { id: 'copy', submenu: [{ id: 'copy-deeplink', onSelect: choose }, { id: 'delete-thread' }] },
    { id: 'pin-thread' }, { id: 'archive-thread', onSelect: choose }, { id: 'delete-thread' },
  ]);
  assert.equal(items.map((item) => item.id).join(','), 'rename-thread,share-thread,copy,vcl-archive-separator,archive-thread');
  assert.equal(items[0].onSelect, choose, '原生动作引用必须原样保留');
  assert.equal(items[1].enabled, false, '保留原生能力限制');
  assert.equal(items[2].submenu.length, 1);
  let archived;
  const unsubscribeArchived = bridge.subscribeThreadArchived((id) => { archived = id; });
  bridge.threadArchived('other'); assert.equal(archived, 'other');
  unsubscribeArchived(); bridge.threadArchived('current'); assert.equal(archived, 'other');
  releaseMenu(); assert.equal(bridge.threadMenuTarget(), null);
  await assert.rejects(bridge.restoreArchivedThread({ id: 'saved' }), /尚未就绪/);
  const restoredTargets = [];
  const removeArchiveActions = bridge.registerArchiveActions({}, { restore: async (target) => {
    restoredTargets.push(target); return { restored: true };
  } });
  const saved = { id: 'saved', title: '归档聊天' };
  const restoring = bridge.restoreArchivedThread(saved); saved.id = 'other';
  assert.equal((await restoring).restored, true);
  assert.equal(restoredTargets[0].id, 'saved', '异步恢复必须绑定点击时的聊天编号');
  await assert.rejects(bridge.restoreArchivedThread({ id: '../invalid' }), /编号无效/);
  assert.equal(restoredTargets.length, 1);
  removeArchiveActions();
  await assert.rejects(bridge.restoreArchivedThread({ id: 'saved' }), /尚未就绪/);
  assert.equal(bridge.reasoningEnabled(), false);
  let reasoningChanges = 0;
  bridge.subscribeReasoning(() => { throw new Error('broken reasoning subscriber'); });
  const unsubscribeReasoning = bridge.subscribeReasoning(() => { reasoningChanges += 1; });
  bridge.setReasoningEnabled(true);
  assert.equal(bridge.reasoningEnabled(), true);
  bridge.setReasoningEnabled(true);
  assert.equal(reasoningChanges, 1);
  bridge.setReasoningEnabled(false);
  assert.equal(bridge.reasoningEnabled(), false);
  assert.equal(reasoningChanges, 2);
  unsubscribeReasoning();
  bridge.setReasoningEnabled(true);
  assert.equal(reasoningChanges, 2);
  const readerCalls = [];
  let finishOpening;
  const removeReader = bridge.setReasoningReader((method, detail) => {
    readerCalls.push({ method, detail });
    if (method === 'open-reasoning-view') return new Promise((resolve) => { finishOpening = resolve; });
  });
  const props = { hostId: 'local', conversationId: 'thread', item: { sourceItemId: 'summary', content: '第一段', completed: false } };
  bridge.updateReasoningView(props);
  assert.equal(readerCalls.length, 0, '未点击阅读入口时不转发摘要正文');
  bridge.openReasoningView(props);
  bridge.updateReasoningView({ ...props, item: { ...props.item, content: '第一段\n第二段' } });
  bridge.updateReasoningView({ ...props, hostId: 'another-host' });
  assert.equal(readerCalls.length, 1, '等待阅读视图打开且排除其他宿主');
  finishOpening();
  await new Promise((resolve) => setImmediate(resolve));
  assert.equal(readerCalls.length, 2);
  assert.equal(readerCalls[1].detail.content, '第一段\n第二段');
  removeReader();
  bridge.updateReasoningView(props);
  bridge.openReasoningView(props);
  assert.equal(readerCalls.length, 2, '销毁阅读入口后停止转发');
  const snapshots = [];
  bridge.subscribe((value) => snapshots.push(value));
  bridge.subscribe(() => { throw new Error('addon error'); });
  officialApi.postMessage({ type: 'ready' });
  bridge.observeRoute('/local/another');
  await new Promise((resolve) => setImmediate(resolve));
  assert.equal(snapshots.at(-1).route, '/local/another');
  assert.equal(snapshots.at(-1).ready, true);
  bridge.postMessage({ type: 'vscodex-layer/request', id: 'one' });
  assert.equal(messages.length, 2);
  assert.equal(calls, 1);
  let resumed = 0;
  assert.equal(bridge.resumeDraft(), false);
  const remove = bridge.setNewChatHandler(() => { resumed += 1; });
  assert.equal(bridge.resumeDraft({ selectChat: true }), true);
  assert.equal(bridge.resumeDraft({ freshDraft: true }), true);
  assert.equal(bridge.resumeDraft({ prefillPrompt: '用户明确预填' }), false);
  assert.equal(bridge.resumeDraft({ activeProject: null }), false);
  assert.equal(bridge.resumeDraft({ prefillComposerDraft: { text: 'rich draft' } }), false);
  assert.equal(resumed, 2);
  assert.equal(state.draft, 'updated');
  remove();
  assert.equal(bridge.resumeDraft(), false);
  const project = bridge.projectRoute('/', '/', '?vclProjectCwd=D%3A%5COther%5CProject');
  assert.equal(project.vclProjectCwd, 'D:\\Other\\Project');
  assert.equal(project.vclDraftKey, bridge.projectRoute('/', '/', '?vclProjectCwd=d%3A%2Fother%2Fproject%2F').vclDraftKey);
  assert.notEqual(project.vclDraftKey, bridge.projectRoute('/', '/', '?vclProjectCwd=D%3A%5CCurrent%5CProject').vclDraftKey);
  assert.notEqual(project.vclDraftKey, bridge.projectRoute('/extension/panel/new', '/', '?vclProjectCwd=D%3A%5COther%5CProject').vclDraftKey);
  const linuxDraft = (cwd, pathname = '/') => bridge.projectRoute(pathname, '/', `?vclProjectCwd=${encodeURIComponent(cwd)}`).vclDraftKey;
  assert.notEqual(linuxDraft('/home/ubuntu/Project'), linuxDraft('/home/ubuntu/project'));
  assert.equal(linuxDraft('/home/ubuntu/Project/'), linuxDraft('/home/ubuntu/Project'));
  assert.notEqual(linuxDraft('/home/ubuntu/a\\b'), linuxDraft('/home/ubuntu/a/b'));
  assert.notEqual(linuxDraft('/'), linuxDraft(''));
  assert.notEqual(linuxDraft('/home/ubuntu/Project'), linuxDraft('/home/ubuntu/Project', '/extension/panel/new'));
  assert.equal(bridge.projectRoute('/local/another', '/', '?vclProjectCwd=D%3A%5COther%5CProject'), null);
  assert.equal(bridge.projectRoute('/', '/', ''), null);
  assert.equal(bridge.projectCwd({ kind: 'local', vclProjectCwd: 'D:\\Other' }), undefined);
  await assert.rejects(bridge.validateProject('D:\\Other'), /尚未就绪/);
  bridge.setProjectValidator(async (cwd) => ({ cwd }));
  assert.equal((await bridge.validateProject('D:\\Other')).cwd, 'D:\\Other');
  assert.throws(() => vm.runInContext('acquireVsCodeApi()', context), /already acquired/);
});
